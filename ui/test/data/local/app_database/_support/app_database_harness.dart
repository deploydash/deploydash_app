  CipherProbeDatabase(this._rows);

  final sqlite.ResultSet _rows;

  @override
  sqlite.ResultSet select(
    String sql, [
    List<Object?> parameters = const <Object?>[],
  ]) => _rows;

  @override
  dynamic noSuchMethod(Invocation invocation) => super.noSuchMethod(invocation);
}
